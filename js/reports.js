/**
 * 获取排名前N的子维度（得分最高的）
 */
function getTopSubDimensions(subScores, count) {
  const all = [
    { key: 'fear', score: subScores.anxSubs.fear, category: 'anxiety' },
    { key: 'hypervigilance', score: subScores.anxSubs.hypervigilance, category: 'anxiety' },
    { key: 'lowSelfWorth', score: subScores.anxSubs.lowSelfWorth, category: 'anxiety' },
    { key: 'distance', score: subScores.avoSubs.distance, category: 'avoidance' },
    { key: 'expression', score: subScores.avoSubs.expression, category: 'avoidance' },
    { key: 'independence', score: subScores.avoSubs.independence, category: 'avoidance' }
  ];

  // 按得分降序排列，取前N个
  return all.sort((a, b) => b.score - a.score).slice(0, count);
}

/**
 * 生成完整报告
 * @param {Object} result - getAttachmentResult 的返回值
 * @returns {Object} 报告对象
 */
function generateReport(result) {
  const typeKey = result.type.key;
  const scores = result.scores;
  const subScores = result.subScores;

  // 模块1：类型总览
  const typeOverview = TYPE_OVERVIEW[typeKey];

  // 模块2：维度得分解读
  const anxAnalysis = DIMENSION_ANALYSIS.anxiety[result.anxietyLevel];
  const avoAnalysis = DIMENSION_ANALYSIS.avoidance[result.avoidanceLevel];

  // 模块3+4：核心模式深度分析（取得分最高的2-3个子维度）
  const topSubs = getTopSubDimensions(subScores, 3);
  const deepDiveSections = topSubs.map(sub => {
    const subData = SUB_DIMENSION_ANALYSIS[sub.key];
    const level = sub.category === 'anxiety'
      ? result.anxSubLevels[sub.key]
      : result.avoSubLevels[sub.key];
    return {
      title: subData.name,
      content: subData[level]
    };
  });

  // 模块5：通用内容
  const general = GENERAL_CONTENT[typeKey];

  // 模块6：改善建议（根据核心子维度匹配）
  const suggestionKeys = topSubs.slice(0, 2).map(s => s.key);
  const suggestionTexts = suggestionKeys.map(key => SUGGESTIONS[key] || '').filter(Boolean);

  return {
    typeOverview,
    dimensionAnalysis: {
      anxiety: anxAnalysis,
      avoidance: avoAnalysis,
      anxietyScore: scores.anxiety,
      avoidanceScore: scores.avoidance,
      anxietyLevel: result.anxietyLevel,
      avoidanceLevel: result.avoidanceLevel
    },
    deepDive: deepDiveSections,
    general,
    suggestions: suggestionTexts
  };
}